def _mean(xs: Sequence[float]) -> float:
    return statistics.fmean(xs) if xs else 0.0


def _median(xs: Sequence[float]) -> float:
    return statistics.median(xs) if xs else 0.0


def _f1(precision: float, recall: float) -> float:
    return 2*precision*recall/(precision+recall) if precision+recall else 0.0


def make_pair(seed: int, *, n_events: int = 50, dropout: float = 0.10,
              false_events: int = 5, nonlinear_drift: float = 0.0,
              mark_noise: float = 0.008, time_jitter: float = 0.0015,
              shuffle_b_order: bool = False,
              shuffle_b_marks: bool = False) -> tuple[EventStream, EventStream, list[int | None], list[int | None], dict]:
    rng = random.Random(seed)
    gaps = [0.25 + rng.expovariate(1.15) for _ in range(n_events-1)]
    latent_times = [0.0]
    for gap in gaps:
        latent_times.append(latent_times[-1] + gap)
    duration = latent_times[-1] or 1.0
    latent_marks = [rng.random() for _ in range(n_events)]

    # Observer A retains the reference event order, but has its own origin,
    # rate and measurement jitter.
    offset_a, scale_a = 2.0, 1.0
    a_times = [offset_a + scale_a*t + rng.gauss(0, time_jitter) for t in latent_times]
    # Ensure strict order if rare jitter crossings occur.
    for i in range(1, len(a_times)):
        a_times[i] = max(a_times[i], a_times[i-1] + 1e-5)
    a_marks = [m + rng.gauss(0, mark_noise) for m in latent_marks]
    a_items = [(a_times[i], a_marks[i], i) for i in range(n_events)]

    # Observer B runs an independent clock. The quadratic term is a controlled
    # non-affine drift; its derivative remains positive for tested strengths.
    offset_b, scale_b = 17.0, 2.75
    b_true = []
    for i, t in enumerate(latent_times):
        if rng.random() < dropout:
            continue
        tb = offset_b + scale_b*t + nonlinear_drift*(t*t/duration)
        tb += rng.gauss(0, time_jitter)
        mark = 1.7 + 3.1*latent_marks[i] + rng.gauss(0, mark_noise)
        b_true.append((tb, mark, i))

    if shuffle_b_order:
        # Assign true event identities/marks to a chronological set of B times
        # in a random order: same inventory, destroyed temporal correspondence.
        b_times = sorted(x[0] for x in b_true)
        identity_mark = [(x[2], x[1]) for x in b_true]
        rng.shuffle(identity_mark)
        b_true = [(b_times[i], identity_mark[i][1], identity_mark[i][0])
                  for i in range(len(b_times))]

    if shuffle_b_marks and b_true:
        marks = [x[1] for x in b_true]
        rng.shuffle(marks)
        b_true = [(b_true[i][0], marks[i], b_true[i][2]) for i in range(len(b_true))]

    b_items = list(b_true)
    for _ in range(false_events):
        t = offset_b + scale_b*rng.random()*duration
        t += nonlinear_drift*((max(0.0, t-offset_b)/scale_b)**2/duration)
        b_items.append((t, 1.7 + 3.1*rng.random() + rng.gauss(0, 0.04), None))
    b_items.sort(key=lambda x: x[0])
    # Resolve any numerical ties in local clock timestamps.
    fixed = []
    for item in b_items:
        t, mark, event_id = item
        if fixed and t <= fixed[-1][0]:
            t = fixed[-1][0] + 1e-5
        fixed.append((t, mark, event_id))

    left = EventStream("observer_A", tuple(x[0] for x in a_items), tuple(x[1] for x in a_items),
                       duration_s=(a_times[-1]-a_times[0])+1.0)
    right = EventStream("observer_B", tuple(x[0] for x in fixed), tuple(x[1] for x in fixed),
                        duration_s=(fixed[-1][0]-fixed[0][0])+1.0 if fixed else 1.0)
    meta = {"n_latent": n_events, "dropout": dropout, "false_events": false_events,
            "nonlinear_drift": nonlinear_drift, "mark_noise_sd": mark_noise,
            "time_jitter_sd": time_jitter, "offset_A": offset_a, "scale_A": scale_a,
            "offset_B": offset_b, "scale_B": scale_b, "latent_duration": duration}
    return left, right, [x[2] for x in a_items], [x[2] for x in fixed], meta


def score_alignment(left: EventStream, right: EventStream,
                    left_ids: Sequence[int | None], right_ids: Sequence[int | None],
                    alignment: dict) -> dict:
    true_common = {x for x in right_ids if x is not None}
    matched_correct = 0
    for m in alignment["matches"]:
        a_id, b_id = left_ids[m["left_index"]], right_ids[m["right_index"]]
        if a_id is not None and b_id is not None and a_id == b_id:
            matched_correct += 1
    predicted = len(alignment["matches"])
    precision = matched_correct / predicted if predicted else 0.0
    recall = matched_correct / len(true_common) if true_common else 0.0
    return {"true_positives": matched_correct, "predicted_matches": predicted,
            "true_common_events": len(true_common), "precision": precision,
            "recall": recall, "f1": _f1(precision, recall),
            "left_coverage": alignment["left_coverage"],
            "right_coverage": alignment["right_coverage"]}


def evaluate_weights(seeds: Sequence[int], *, mark_weight: float,
                     interval_weight: float, nonlinear_drift: float = 0.0,
                     shuffle_b_marks: bool = False,
                     shuffle_b_order: bool = False) -> dict:
    rows = []
    for seed in seeds:
        left, right, left_ids, right_ids, meta = make_pair(
            seed, nonlinear_drift=nonlinear_drift,
            shuffle_b_marks=shuffle_b_marks, shuffle_b_order=shuffle_b_order)
        alignment = align_event_streams(left, right, mark_weight=mark_weight,
                                        interval_weight=interval_weight)
        rows.append(score_alignment(left, right, left_ids, right_ids, alignment))
    return {"trials": len(rows), "mark_weight": mark_weight,
            "interval_weight": interval_weight,
            "mean_precision": _mean([r["precision"] for r in rows]),
            "mean_recall": _mean([r["recall"] for r in rows]),
            "mean_f1": _mean([r["f1"] for r in rows]),
            "median_f1": _median([r["f1"] for r in rows]),
            "mean_left_coverage": _mean([r["left_coverage"] for r in rows]),
            "mean_right_coverage": _mean([r["right_coverage"] for r in rows]),
            "trial_metrics": rows}


def run_falsification_suite(seed_count: int = 40) -> dict:
    seeds = list(range(1600, 1600+seed_count))
    ablations = {
        "mark_only": evaluate_weights(seeds, mark_weight=1.0, interval_weight=0.0),
        "interval_only": evaluate_weights(seeds, mark_weight=0.0, interval_weight=1.0),
        "combined_0.78_0.22": evaluate_weights(seeds, mark_weight=0.78, interval_weight=0.22),
        "equal_weights": evaluate_weights(seeds, mark_weight=0.5, interval_weight=0.5),
    }
    controls = {
        "independently_shuffled_B_marks": evaluate_weights(
            seeds, mark_weight=0.78, interval_weight=0.22, shuffle_b_marks=True),
        "shuffled_B_event_order": evaluate_weights(
            seeds, mark_weight=0.78, interval_weight=0.22, shuffle_b_order=True),
    }
    drift = {}
    for severity in (0.0, 0.05, 0.15, 0.30, 0.60):
        drift[f"quadratic_drift_{severity:.2f}"] = {
            "mark_only": evaluate_weights(seeds, mark_weight=1.0, interval_weight=0.0,
                                          nonlinear_drift=severity),
            "interval_only": evaluate_weights(seeds, mark_weight=0.0, interval_weight=1.0,
                                              nonlinear_drift=severity),
            "combined": evaluate_weights(seeds, mark_weight=0.78, interval_weight=0.22,
                                         nonlinear_drift=severity),
        }
    return {
        "build": 16,
        "provenance": "synthetic_controlled_event_streams_only",
        "trial_count_per_condition": seed_count,
        "ablation_results": ablations,
        "negative_controls": controls,
        "nonlinear_clock_drift_sweep": drift,
        "important_caveat": (
            "Event marks are shared latent-event descriptors with monotone affine channel transforms. "
            "Mark-only ablation tests reliance on that cue; it does not demonstrate a general-purpose "
            "clock-free correspondence method. Real sensor event marks may not be stable across observers."
        ),
    }


def run_harmonic_demo() -> dict:
    # Exact finite DFT test on a mixed periodic signal.
    x = [complex(math.sin(2*math.pi*3*n/32) + 0.35*math.cos(2*math.pi*7*n/32),
                 0.1*math.sin(2*math.pi*2*n/32)) for n in range(32)]
    dft_diag = fourier_diagnostics(x)
    x_shift = circular_shift(x, 5)
    mag0, mag1 = spectrum_magnitude(x), spectrum_magnitude(x_shift)
    shift_error = max(abs(a-b) for a,b in zip(mag0, mag1))

    # A small temporal event graph. Its graph Fourier basis is derived from
    # the Laplacian rather than imported from the linear time axis.
    latent = [0.0]
    gaps = [0.7, 0.9, 0.7, 1.4, 0.7, 0.9, 0.7, 1.4, 0.7, 0.9, 0.7, 1.4, 0.8]
    for g in gaps:
        latent.append(latent[-1]+g)
    marks = [0.2,0.7,0.4,0.9,0.3,0.8,0.5,0.6,0.25,0.75,0.45,0.95,0.35,0.85]
    left = EventStream("demo_A", tuple(latent), tuple(marks), duration_s=latent[-1]+1)
    right = EventStream("demo_B", tuple(9.0+2.4*t for t in latent),
                        tuple(1.5+2.1*m for m in marks), duration_s=2.4*latent[-1]+2)
    pair = analyze_stream_pair(left, right)
    graph = pair["graph"]
    adjacency = event_graph_adjacency(graph, observer_prefix="L")
    signal = marks
    gft = graph_fourier(adjacency, signal)
    eigenvalues = gft["eigenvalues"]
    # Isomorphic relabeling check: spectrum invariant under simultaneous row/
    # column permutation. Individual eigenvectors are not treated as invariant.
    perm = list(reversed(range(len(adjacency))))
    permuted = permute_square_matrix(adjacency, perm)
    perm_eigenvalues, _ = symmetric_jacobi_eigensystem(graph_laplacian(permuted))
    perm_error = max(abs(a-b) for a,b in zip(eigenvalues, perm_eigenvalues))
    return {
        "provenance": "synthetic_deterministic_fixture",
        "finite_dft": dft_diag,
        "circular_shift_magnitude_invariance_max_abs_error": shift_error,
        "event_graph_fourier": {
            "node_count": len(adjacency),
            "laplacian_eigenvalues": eigenvalues,
            "eigenvalue_multiplicity_groups": eigenvalue_multiplicity_groups(eigenvalues),
            "input_signal_energy": gft["input_energy"],
            "spectral_energy": gft["spectral_energy"],
            "parseval_abs_error": gft["parseval_abs_error"],
            "reconstruction_max_abs_error": gft["reconstruction_max_abs_error"],
            "permutation_spectrum_max_abs_error": perm_error,
            "interpretation": (
                "Graph Fourier modes diagonalize the chosen graph Laplacian. The spectrum is "
                "invariant under node relabeling, but is not a complete graph isomorphism test; "
                "eigenvectors inside repeated eigenspaces are not individually canonical."
            ),
        },
        "cross_representation_note": (
            "The ordinary DFT is tied to cyclic translation on an ordered finite sequence. "
            "The graph Fourier transform is tied to the chosen graph Laplacian. They answer "
            "different symmetry questions and should not be treated as interchangeable."
        ),
    }


def write_reports(root: Path) -> dict:
    root.mkdir(parents=True, exist_ok=True)
    stress = run_falsification_suite()
    harmonic = run_harmonic_demo()
    (root/"falsification_controls.json").write_text(json.dumps(stress, indent=2), encoding="utf-8")
    (root/"harmonic_representation_demo.json").write_text(json.dumps(harmonic, indent=2), encoding="utf-8")
    summary = {
        "build": 16,
        "status": "synthetic_falsification_and_harmonic_prototypes_complete",
        "empirical_sensor_data_processed": False,
        "falsification_trial_count_per_condition": stress["trial_count_per_condition"],
        "harmonic_dft_parseval_error": harmonic["finite_dft"]["parseval_abs_error"],
        "graph_fourier_parseval_error": harmonic["event_graph_fourier"]["parseval_abs_error"],
        "graph_spectrum_permutation_error": harmonic["event_graph_fourier"]["permutation_spectrum_max_abs_error"],
        "source_data_status": "no empirical sensor input; generated event fixtures only",
    }
    (root/"build_16_status.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return {"stress": stress, "harmonic": harmonic, "summary": summary}


